/** Package prefixes a Maven group's classes may live under. */
export function groupPackages(group: string): string[] {
  const out = new Set<string>(GROUP_PACKAGES[group] ?? []);
  out.add(group);
  // `com.fasterxml.jackson.core:jackson-databind` lives in `com.fasterxml.jackson.databind`.
  const parts = group.split(".");
  if (parts.length >= 3) out.add(parts.slice(0, -1).join("."));
  return [...out];
}
