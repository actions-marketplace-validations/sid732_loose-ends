/** PEP 503 name normalization. */
export function normalizeDist(name: string): string {
  return name.toLowerCase().replace(/[-_.]+/g, "-");
}

/** Import names a distribution is likely to provide. */
export function importNames(dist: string): string[] {
  const norm = normalizeDist(dist);
  const known = IMPORT_NAMES[norm];
  const out = new Set<string>(known ?? []);
  const base = norm.replace(/-/g, "_");
  out.add(base);
  for (const stripped of [norm.replace(/^(python|py)-/, ""), norm.replace(/-(python|py)$/, ""), norm.replace(/^django-/, ""), norm.replace(/^flask-/, "flask_")]) {
    out.add(stripped.replace(/-/g, "_"));
  }
  // Namespace distributions: `google-cloud-storage` -> google, `azure-identity` -> azure, `zope.interface` -> zope.
  if (/^(google|azure|zope|jaraco|sphinxcontrib|backports|opentelemetry|ruamel)-/.test(norm)) out.add(norm.split("-")[0]!);
  return [...out];
}
