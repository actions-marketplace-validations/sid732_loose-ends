import { describe, expect, it } from "vitest";
import { allSuppressions, analyze, fileId, loadConfig, parseModule, stateOf, symbolId } from "@loose-ends/core";
import { project } from "./helpers/project.js";

describe("directive parsing", () => {
  it("reads declaration and file directives", () => {
    const info = parseModule(
      "a.ts",
      `// loose-ends-file: ignore uncertain generated by openapi
import x from "y";

/** Old exporter.
 * loose-ends: dormant kept for the v1 webhook payload
 */
export function exportV1() {}

// loose-ends: entry
export const handler = () => {};

// loose-ends: dormant
function noReason() {}
`,
    );
    expect(info.directives).toEqual([
      { scope: "file", action: "ignore", kind: "uncertain", reason: "generated by openapi", line: 1, symbols: [] },
      { scope: "declaration", action: "dormant", reason: "kept for the v1 webhook payload", line: 4, symbols: ["exportV1"], kind: undefined },
      { scope: "declaration", action: "entry", reason: "", line: 9, symbols: ["handler"], kind: undefined },
      { scope: "declaration", action: "dormant", reason: "", line: 12, symbols: ["noReason"], kind: undefined },
    ]);
  });
});

describe("dormant and entry handling", () => {
  const files = {
    "package.json": { name: "app", main: "index.ts" },
    "loose-ends.config.json": {
      dormant: [{ target: "legacy/**", reason: "kept until the migration finishes" }, { target: "nothing/**", reason: "typo" }],
      suppressions: [{ target: "index.ts#x", reason: "reviewed", kind: "orphaned-addition" }],
    },
    "index.ts": "export const x = 1;",
    "legacy/old.ts": "import { helper } from '../shared';\nexport function old() { return helper(); }",
    "shared.ts": "export function helper() {}",
    "jobs/cron.ts": "// loose-ends-file: entry\nexport function nightly() {}",
    "hooks.ts": "// loose-ends: dormant re-enabled when billing ships\nexport function onInvoice() {}\n// loose-ends: ignore orphaned-addition temporary\nexport function draft() {}\n// loose-ends: dormant\nexport function bare() {}",
  };

  it("marks dormant code and everything only it uses", () => {
    const a = analyze(loadConfig(project(files)));
    expect(stateOf(a, fileId("legacy/old.ts")).liveness).toBe("dormant");
    expect(stateOf(a, symbolId("shared.ts", "helper")).liveness).toBe("dormant");
    expect(stateOf(a, symbolId("shared.ts", "helper")).note).toMatch(/only used by dormant code/);
    expect(stateOf(a, symbolId("hooks.ts", "onInvoice")).liveness).toBe("dormant");
    expect(stateOf(a, symbolId("hooks.ts", "bare")).liveness).toBe("orphaned");
  });

  it("treats entry directives as production roots", () => {
    const a = analyze(loadConfig(project(files)));
    expect(stateOf(a, symbolId("jobs/cron.ts", "nightly")).liveness).toBe("live");
  });

  it("reports unusable dormant markers", () => {
    const a = analyze(loadConfig(project(files)));
    expect(a.problems.map((p) => p.message)).toEqual(['dormant rule "nothing/**" matches no code', "dormant directive needs a reason"]);
  });

  it("collects config and inline suppressions", () => {
    const a = analyze(loadConfig(project(files)));
    expect(allSuppressions(a).map((s) => [s.target, s.kind, s.reason])).toEqual([
      ["index.ts#x", "orphaned-addition", "reviewed"],
      ["hooks.ts#draft", "orphaned-addition", "temporary"],
    ]);
  });
});
